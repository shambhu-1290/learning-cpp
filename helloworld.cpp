#include <iostream>
using namespace std;

// Understanding the concept of variables in C++ programming language. 
int main()
{
    int va = 3;            // 3 was stored in var_a location
    int varb = 5;          // 5 was stored in var_v location
    int var_c = va * varb; // var_a multiply var_b value was stored in var_c
    cout << var_c;         // console output or we just print var_c
    return 0;
}
